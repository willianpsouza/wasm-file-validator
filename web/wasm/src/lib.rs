//! wasm_file_validator
//!
//! Browser-side validator. Given raw file bytes it:
//!   1. inspects the file (zip-bomb heuristics, JPEG/GIF polyglot/worm carriers),
//!   2. signs the resulting verdict with an embedded Ed25519 key,
//!   3. seals (ECDH x25519 + XChaCha20-Poly1305) the signed verdict to the
//!      backend's public key, producing an opaque base64 envelope.
//!
//! SECURITY: the Ed25519 *signing* key is embedded in client code. Anyone can
//! extract it from the published .wasm, so the signature proves nothing about
//! origin in this demo — it only demonstrates the mechanism. See README.

mod keys_gen; // generated by `go run ./cmd/genkeys` (git-ignored)
mod validate;

use base64::{engine::general_purpose::STANDARD as B64, Engine as _};
use chacha20poly1305::{aead::Aead, aead::Payload, KeyInit, XChaCha20Poly1305, XNonce};
use ed25519_dalek::{Signer, SigningKey};
use hkdf::Hkdf;
use rand_core::{OsRng, RngCore};
use serde::Serialize;
use sha2::Sha256;
use wasm_bindgen::prelude::*;
use x25519_dalek::{EphemeralSecret, PublicKey};

const HKDF_INFO: &[u8] = b"wasm-file-validator-v1";

#[derive(Serialize)]
struct Sealed {
    report_b64: String,
    sig_b64: String,
}

#[derive(Serialize)]
struct Output {
    report: validate::Report,
    payload: String,
}

/// Inspect `data`, sign + seal the verdict, return JSON `{report, payload}`.
#[wasm_bindgen]
pub fn validate_and_seal(data: &[u8]) -> Result<String, JsValue> {
    let report = validate::inspect(data);

    // --- sign the canonical verdict bytes with the embedded Ed25519 key ---
    let report_json = serde_json::to_vec(&report).map_err(js_err)?;
    let signing = SigningKey::from_bytes(&keys_gen::ED25519_SEED);
    let sig = signing.sign(&report_json);

    let sealed = Sealed {
        report_b64: B64.encode(&report_json),
        sig_b64: B64.encode(sig.to_bytes()),
    };
    let plaintext = serde_json::to_vec(&sealed).map_err(js_err)?;

    // --- seal to the backend's x25519 public key (anonymous sender) ---
    let envelope = seal_to_backend(&plaintext)?;

    let out = Output {
        report,
        payload: B64.encode(&envelope),
    };
    serde_json::to_string(&out).map_err(js_err)
}

/// envelope = ephemeral_pub(32) || nonce(24) || ciphertext
fn seal_to_backend(plaintext: &[u8]) -> Result<Vec<u8>, JsValue> {
    let server_pub = PublicKey::from(keys_gen::SERVER_X25519_PUB);

    let eph_secret = EphemeralSecret::random_from_rng(OsRng);
    let eph_pub = PublicKey::from(&eph_secret);
    let shared = eph_secret.diffie_hellman(&server_pub);

    // HKDF-SHA256(shared) -> 32-byte AEAD key
    let hk = Hkdf::<Sha256>::new(None, shared.as_bytes());
    let mut key = [0u8; 32];
    hk.expand(HKDF_INFO, &mut key)
        .map_err(|_| JsValue::from_str("hkdf expand failed"))?;

    let cipher = XChaCha20Poly1305::new((&key).into());
    let mut nonce_bytes = [0u8; 24];
    OsRng.fill_bytes(&mut nonce_bytes);
    let nonce = XNonce::from_slice(&nonce_bytes);

    // bind the ephemeral public key as AAD so it can't be swapped
    let ct = cipher
        .encrypt(
            nonce,
            Payload {
                msg: plaintext,
                aad: eph_pub.as_bytes(),
            },
        )
        .map_err(|_| JsValue::from_str("aead encrypt failed"))?;

    let mut envelope = Vec::with_capacity(32 + 24 + ct.len());
    envelope.extend_from_slice(eph_pub.as_bytes());
    envelope.extend_from_slice(&nonce_bytes);
    envelope.extend_from_slice(&ct);
    Ok(envelope)
}

fn js_err<E: std::fmt::Display>(e: E) -> JsValue {
    JsValue::from_str(&e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn seal_structure_and_freshness() {
        let a = seal_to_backend(b"hello world").expect("seal a");
        let b = seal_to_backend(b"hello world").expect("seal b");
        // envelope = ephemeral_pub(32) || nonce(24) || ciphertext(>=16 tag)
        assert!(a.len() >= 32 + 24 + 16);
        // fresh ephemeral key + nonce every call -> different ciphertext
        assert_ne!(a, b);
        assert_ne!(&a[..32], &b[..32], "ephemeral public key must differ");
    }

    #[test]
    fn validate_and_seal_outputs_report_and_payload() {
        let out =
            validate_and_seal(b"%PDF-1.7\n<< /OpenAction 1 0 R >> /JavaScript\n%%EOF\n").unwrap();
        let v: serde_json::Value = serde_json::from_str(&out).unwrap();
        assert_eq!(v["report"]["file_type"], "pdf");
        assert_eq!(v["report"]["verdict"], "malicious");
        assert!(v["payload"].as_str().unwrap().len() > 50);
    }

    #[test]
    fn signs_with_embedded_key() {
        use ed25519_dalek::{Verifier, VerifyingKey};
        let signing = SigningKey::from_bytes(&keys_gen::ED25519_SEED);
        let msg = b"verdict bytes";
        let sig = signing.sign(msg);
        let vk: VerifyingKey = signing.verifying_key();
        assert!(vk.verify(msg, &sig).is_ok());
    }
}
